fn panicWriterError(as: *Assembler) noreturn {
    @branchHint(.cold);
    std.debug.panic("{t}", .{as.out.err.?});
}

/// Don't forget the newline at the end!
fn print(as: *Assembler, str: []const u8) void {
    as.out.interface.writeAll(str) catch as.panicWriterError();
}

/// Don't forget the newline at the end!
fn printMany(as: *Assembler, strings: []const []const u8) void {
    for (strings) |s| {
        as.print(s);
    }
}

const PrintIntBase = enum(u5) { dec = 10, hex = 16 };

const PrintIntOptions = struct {
    width: ?usize = null,
    fill: u8 = '0',
};

fn printIntWithOptions(
    as: *Assembler,
    value: anytype,
    base: PrintIntBase,
    options: PrintIntOptions,
) void {
    switch (base) {
        .dec => {},
        .hex => as.print("0x"),
    }

    as.out.interface.printInt(value, @intFromEnum(base), .upper, .{
        .width = options.width,
        .fill = options.fill,
    }) catch as.panicWriterError();
}

fn printInt(as: *Assembler, value: anytype) void {
    as.printIntWithOptions(value, .dec, .{});
}

pub fn writeComment(
    as: *Assembler,
    /// Shouldn't contain embedded newlines.
    comment: []const u8,
) void {
    as.printMany(&.{ "# ", comment, "\n" });
}

pub fn writeCommentMultiLine(
    as: *Assembler,
    /// Shouldn't contain embedded newlines.
    comments: []const []const u8,
) void {
    for (comments) |s| {
        as.writeComment(s);
    }
}

fn nextNumberedLabel(as: *Assembler) u32 {
    const num = as.label_counter;
    as.label_counter += 1;
    return num;
}

pub const Label = struct {
    name_ptr: [*]const u8,
    name_len: u16,
    placed: bool = false,
    number: u32,
    function_name: [*]const u8,

    fn name(l: Label) []const u8 {
        return l.name_ptr[0..l.name_len];
    }

    pub fn place(l: *Label, as: *Assembler) void {
        std.debug.assert(!l.placed);
        l.placed = true;
        as.printLabelName(l);
        as.print(":\n");
    }
};

fn printLabelName(as: *Assembler, l: *const Label) void {
    const func_name = as.function_name.?;
    std.debug.assert(@intFromPtr(func_name.ptr) == @intFromPtr(l.function_name));
    as.printMany(&.{ ".L", as.symbol_prefix, func_name, "_", l.name() });
    as.printInt(l.number);
}

pub fn label(as: *Assembler, name: []const u8) Label {
    return .{
        .function_name = as.function_name.?.ptr,
        .name_ptr = name.ptr,
        .name_len = @intCast(name.len),
        .number = as.nextNumberedLabel(),
    };
}

const Function = struct {
    name: [*]const u8,

    pub fn end(func: Function, as: *Assembler) void {
        const func_name = as.function_name.?;
        std.debug.assert(@intFromPtr(func.name) == @intFromPtr(func_name.ptr));

        var end_label = as.label("end");
        end_label.place(as);
        as.printMany(&.{ ".size ", as.symbol_prefix, func_name, ", " });
        as.printLabelName(&end_label);
        as.printMany(&.{ " - ", as.symbol_prefix, func_name });
        as.print("\n# .cfi_endproc\n");
        as.function_name = null;
    }
};

pub fn p2align(as: *Assembler, alignment: std.mem.Alignment) void {
    as.print(".p2align ");
    as.printInt(@intFromEnum(alignment));
    as.print("\n");
}

pub fn startFunction(
    as: *Assembler,
    /// Must match the pattern `[a-zA-Z_0-9\.]`.
    name: []const u8,
    alignment: std.mem.Alignment,
) Function {
    as.function_name = name;
    as.no_clobber_gprs = .initEmpty();
    as.uninitialized_gprs = comptime .initMany(&Gpr.Tag.no_rsp_or_rbp);
    as.printMany(&.{ "\n.globl ", as.symbol_prefix, name });
    as.print("\n");
    as.p2align(alignment);
    as.printMany(&.{ ".type ", as.symbol_prefix, name, ", @function\n" });
    as.printMany(&.{ as.symbol_prefix, name, ":\n" });
    as.print("# .cfi_startproc\n");
    return Function{ .name = name.ptr };
}

pub fn checkRegisterInitialized(as: *Assembler, reg: Gpr.Tag) void {
    if (as.uninitialized_gprs.contains(reg)) {
        @branchHint(.cold);
        std.debug.panic("register {t} is uninitialized", .{reg});
    }
}

pub fn checkRegisterClobber(as: *Assembler, reg: Gpr.Tag) void {
    if (as.no_clobber_gprs.contains(reg)) {
        @branchHint(.cold);
        std.debug.panic(
            "cannot clobber register {s}/{s}/{s}",
            .{ Gpr.qword(reg).name(), Gpr.name(.{ .tag = reg, .size = .dword }), Gpr.name(
                .{ .tag = reg, .size = .word },
            ) },
        );
    }
}

pub const Symbol = struct {
    name_ptr: [*]const u8,
    name_len: u32,
    prefixed: bool,

    pub fn initPrefixed(name: []const u8) Symbol {
        return .{ .name_ptr = name.ptr, .name_len = @intCast(name.len), .prefixed = true };
    }

    pub fn nameUnprefixed(symbol: Symbol) []const u8 {
        return symbol.name_ptr[0..symbol.name_len];
    }

    pub const byte_dispatch_table = Symbol.initPrefixed("byte_dispatch_table");
    pub const out_of_fuel_handler = Symbol.initPrefixed("outOfFuelHandler");
    pub const interrupt_out_of_fuel = Symbol.initPrefixed("interruptOutOfFuel");
};

fn printSymbol(as: *Assembler, sym: Symbol) void {
    if (sym.prefixed) {
        as.print(as.symbol_prefix);
    }
    as.print(sym.nameUnprefixed());
}

pub const Operand = union(enum) {
    gpr: Gpr,
    xmm: Xmm,
    u8: u8,
    u32: u32,
    mem: Mem,
    label: *const Label,
    symbol: Symbol,

    pub fn paramFromRbp(offset: usize, size: Gpr.Size) Operand {
        return .{
            .mem = .{
                .size = .fromGprSize(size),
                .base = .rbp,
                .disp = .{ .literal = @intCast((offset + 2) * 8) },
            },
        };
    }

    pub const Mem = struct {
        size: Size,
        base: ?Gpr = null,
        index: ?Gpr = null,
        scale: Scale = .@"1",
        disp: Displacement = .{ .literal = 0 },

        pub const Size = enum {
            xmmword,
            qword,
            dword,
            word,
            byte,

            pub fn fromGprSize(size: Gpr.Size) Size {
                return switch (size) {
                    inline else => |chosen| @field(Size, @tagName(chosen)),
                };
            }
        };

        pub const Scale = enum(u2) { @"1", @"2", @"4", @"8" };

        pub const Displacement = union(enum) {
            literal: i32,
            symbol: Symbol,

            fn isZero(disp: Displacement) bool {
                return disp == .literal and disp.literal == 0;
            }
        };
    };
};

pub fn instr(
    as: *Assembler,
    name: []const u8,
    operands: []const Operand,
    /// Must not contain any newlines.
    comment: []const u8,
) void {
    as.print("\t");
    as.print(name);
    for (operands, 0..) |op, i| {
        as.print(if (i == 0) " " else ", ");
        switch (op) {
            .gpr => |gpr| {
                if (i == 0) {
                    as.checkRegisterClobber(gpr.tag); // check destination
                    as.uninitialized_gprs.remove(gpr.tag);
                } else {
                    as.checkRegisterInitialized(gpr.tag);
                }
                as.printGpr(gpr);
            },
            .xmm => |xmm| as.print(@tagName(xmm)),
            .symbol => |sym| as.printSymbol(sym),
            .label => |l| as.printLabelName(l),
            inline .u8, .u32 => |value| as.printIntWithOptions(
                value,
                if (value < 0xA) .dec else .hex,
                .{},
            ),
            .mem => |mem| {
                as.print(@tagName(mem.size));
                as.print(" ptr [");
                if (mem.base) |base| {
                    as.printGpr(base);
                }

                if (mem.index) |index| {
                    if (mem.base != null) {
                        as.print(" + ");
                    } else {
                        std.debug.assert(mem.scale != .@"1" or !mem.disp.isZero()); // use base instead
                    }
                    as.printGpr(index);
                }

                if (mem.scale != .@"1") {
                    if (mem.base != null or mem.index != null) {
                        as.print("*");
                    }
                    as.print(@tagName(mem.scale));
                }

                if (!mem.disp.isZero()) {
                    if (mem.base != null or mem.index != null) {
                        as.print(" + ");
                    }
                    switch (mem.disp) {
                        .literal => |disp| as.printIntWithOptions(
                            disp,
                            if (@rem(disp, 16) == 0) .hex else .dec,
                            .{},
                        ),
                        .symbol => |symbol| as.printSymbol(symbol),
                    }
                }

                as.print("]");
            },
        }
    }

    if (comment.len != 0) {
        as.print(" # ");
        as.print(comment);
    }

    as.print("\n");
}

/// Common condition flags used in isntructions such as `jcc`, `cmovcc`, etc.
///
/// Note that `jcc` also has additional conditions not listed here (e.g. `jcxz`).
pub const Condition = enum {
    a,
    ae,
    b,
    be,
    c,
    e,
    g,
    ge,
    l,
    le,
    na,
    nae,
    nb,
    nbe,
    nc,
    ne,
    ng,
    nge,
    nl,
    nle,
    no,
    np,
    ns,
    nz,
    o,
    p,
    pe,
    po,
    s,
    z,

    fn name(cond: Condition, comptime prefix: []const u8, buffer: *[prefix.len + 3]u8) []const u8 {
        const cond_name = @tagName(cond);
        const final_len = prefix.len + cond_name.len;
        @memcpy(buffer[0..prefix.len], prefix);
        @memcpy(buffer[prefix.len..final_len], cond_name);
        return buffer[0..final_len];
    }
};

