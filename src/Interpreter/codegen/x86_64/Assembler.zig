//! Not really an x86-64 assembler, just helps write x86-64 assembly with additional checks.
//!
//! Does not check errors that would be caught by the actual assembler, e.g. using a wrong operand.

out: std.fs.File.Writer,
symbol_prefix: []const u8,
arena: std.heap.ArenaAllocator,
function_name: ?[]const u8 = null,
label_counter: u32 = 0,
/// Which registers should't be modified.
no_clobber_gprs: std.EnumSet(Gpr.Tag) = .initEmpty(),
uninitialized_gprs: std.EnumSet(Gpr.Tag) = .initEmpty(),

const Assembler = @This();

pub fn init(
    writer: std.fs.File.Writer,
    symbol_prefix: []const u8,
    arena: std.heap.ArenaAllocator,
) Assembler {
    var out = writer;
    out.interface.writeAll(
        \\# WASM opcodes implemented in x86-64 assembly, used in the wasmstint interpreter
        \\#
        \\# This file is automatically generated.
        \\
        \\.intel_syntax noprefix
        \\.text
        \\
    ) catch std.debug.panic("{t}", .{out.err.?});
    return .{ .out = out, .symbol_prefix = symbol_prefix, .arena = arena };
}

pub const Gpr = packed struct(u7) {
    tag: Tag,
    size: Size,

    pub const Size = enum(u2) {
        qword,
        dword,
        word,
        byte,
    };

    pub const Tag = enum(u5) {
        a,
        b,
        c,
        d,

        src,
        dst,
        stack,
        base,

        @"8",
        @"9",
        @"10",
        @"11",

        @"12",
        @"13",
        @"14",
        @"15",

        /// Excludes `rbp`.
        pub const system_v_callee_saved: [5]Gpr.Tag = .{ .@"15", .@"14", .@"13", .@"12", .b };

        pub const system_v_parameters: [6]Gpr.Tag = .{ .dst, .src, .d, .c, .@"8", .@"9" };

        pub const no_rsp_or_rbp: [14]Gpr.Tag = .{
            .a,
            .b,
            .c,
            .d,
            .src,
            .dst,
            .@"8",
            .@"9",
            .@"10",
            .@"11",
            .@"12",
            .@"13",
            .@"14",
            .@"15",
        };

        fn setFormatter(set: std.EnumSet(Gpr.Tag)) FormatSet {
            return .{ .set = set };
        }

        const FormatSet = struct {
            set: std.EnumSet(Gpr.Tag),

            pub fn format(f: @This(), writer: *std.Io.Writer) std.Io.Writer.Error!void {
                var start = true;
                var iter = f.set.iterator();
                while (iter.next()) |next| {
                    if (!start) {
                        try writer.writeAll(", ");
                    }
                    start = false;
                    try writer.writeAll(Gpr.qword(next).name());
                }
            }
        };
    };

    pub fn qword(tag: Tag) Gpr {
        return .{ .tag = tag, .size = .qword };
    }

    /// System V scratch register.
    pub const rax = Gpr.qword(.a);
    /// System V callee-saved register.
    pub const rbx = Gpr.qword(.b);
    /// System V scratch register.
    pub const rcx = Gpr.qword(.c);
    /// System V scratch register.
    pub const rdx = Gpr.qword(.d);

    /// System V scratch register.
    pub const rsi = Gpr.qword(.src);
    /// System V scratch register.
    pub const rdi = Gpr.qword(.dst);
    /// The stack-pointer, which for the purposes of writing the interpreter, is almost *never*
    /// modified.
    pub const rsp = Gpr.qword(.stack);
    /// The base/frame pointer, which for the purposes of writing the interpreter, is almost *never*
    /// modified.
    ///
    /// System V callee-saved register.
    ///
    /// Although using `rbp` could result in some code size savings, it allows Zig's panic handler
    /// to unwind the call stack, even when debug info is not emitted.
    pub const rbp = Gpr.qword(.base);

    /// System V scratch register.
    pub const r8 = Gpr.qword(.@"8");
    /// System V scratch register.
    pub const r9 = Gpr.qword(.@"9");
    /// System V scratch register.
    pub const r10 = Gpr.qword(.@"10");
    /// System V scratch register.
    pub const r11 = Gpr.qword(.@"11");

    /// System V callee-saved register.
    pub const r12 = Gpr.qword(.@"12");
    /// System V callee-saved register.
    pub const r13 = Gpr.qword(.@"13");
    /// System V callee-saved register.
    pub const r14 = Gpr.qword(.@"14");
    /// System V callee-saved register.
    pub const r15 = Gpr.qword(.@"15");

    pub const system_v_parameters: [6]Gpr = regs: {
        var regs: [6]Gpr = undefined;
        for (&regs, Tag.system_v_parameters) |*r, tag| {
            r.* = Gpr.qword(tag);
        }
        break :regs regs;
    };

    pub fn withSize(reg: Gpr, size: Size) Gpr {
        var new_reg = reg;
        new_reg.size = size;
        return new_reg;
    }

    pub const eax = Gpr.rax.withSize(.dword);
    pub const ebx = Gpr.rbx.withSize(.dword);
    pub const ecx = Gpr.rcx.withSize(.dword);
    pub const edx = Gpr.rdx.withSize(.dword);
    pub const esi = Gpr.rsi.withSize(.dword);
    pub const edi = Gpr.rdi.withSize(.dword);
    //esp
    //rbp
    pub const r8d = Gpr.r8.withSize(.dword);
    pub const r9d = Gpr.r9.withSize(.dword);
    pub const r10d = Gpr.r10.withSize(.dword);
    pub const r11d = Gpr.r11.withSize(.dword);
    pub const r12d = Gpr.r12.withSize(.dword);
    pub const r13d = Gpr.r13.withSize(.dword);
    pub const r14d = Gpr.r14.withSize(.dword);
    pub const r15d = Gpr.r15.withSize(.dword);

    pub const ax = Gpr.rax.withSize(.word);
    pub const bx = Gpr.rbx.withSize(.word);
    pub const cx = Gpr.rcx.withSize(.word);
    pub const dx = Gpr.rdx.withSize(.word);
    pub const si = Gpr.rsi.withSize(.word);
    pub const di = Gpr.rdi.withSize(.word);
    //sp
    //bp
    pub const r8w = Gpr.r8.withSize(.word);
    pub const r9w = Gpr.r9.withSize(.word);
    pub const r10w = Gpr.r10.withSize(.word);
    pub const r11w = Gpr.r11.withSize(.word);
    pub const r12w = Gpr.r12.withSize(.word);
    pub const r13w = Gpr.r13.withSize(.word);
    pub const r14w = Gpr.r14.withSize(.word);
    pub const r15w = Gpr.r15.withSize(.word);

    pub const al = Gpr.rax.withSize(.byte);
    pub const bl = Gpr.rbx.withSize(.byte);
    pub const cl = Gpr.rcx.withSize(.byte);
    pub const dl = Gpr.rdx.withSize(.byte);
    pub const sil = Gpr.rsi.withSize(.byte);
    pub const dil = Gpr.rdi.withSize(.byte);
    //spl
    //bpl
    pub const r8b = Gpr.r8.withSize(.byte);
    pub const r9b = Gpr.r9.withSize(.byte);
    pub const r10b = Gpr.r10.withSize(.byte);
    pub const r11b = Gpr.r11.withSize(.byte);
    pub const r12b = Gpr.r12.withSize(.byte);
    pub const r13b = Gpr.r13.withSize(.byte);
    pub const r14b = Gpr.r14.withSize(.byte);
    pub const r15b = Gpr.r15.withSize(.byte);

    pub const vip = Gpr.rax;
    pub const stp = Gpr.rbx;
    pub const fuel = Gpr.rcx; // small savings if moved to other register, cl used for shift
    pub const module = Gpr.rdx; // TODO: infrequently used, small code size savings if moved to r8-15
    pub const vsp = Gpr.rsi;
    pub const locals = Gpr.rdi; // TODO: infrequently used, small code size savings if moved to r8-15
    pub const mems = Gpr.r8;
    pub const interp = Gpr.r9;
    pub const eip = Gpr.r10;
    // r11
    pub const disp = Gpr.r12;

    pub const interpreter_state =
        [10]Gpr{ .vip, .stp, .fuel, .module, .vsp, .locals, .mems, .interp, .eip, .disp };

    pub fn sliceToTagSet(registers: []const Gpr) std.EnumSet(Tag) {
        var tags = std.EnumSet(Gpr.Tag).initEmpty();
        for (registers) |reg| {
            tags.insert(reg.tag);
        }
        return tags;
    }

    pub fn name(reg: Gpr) []const u8 {
        return switch (reg.tag) {
            inline .a, .b, .c, .d => |tag| switch (reg.size) {
                .qword => &[3]u8{ 'r', @tagName(tag)[0], 'x' },
                .dword => &[3]u8{ 'e', @tagName(tag)[0], 'x' },
                .word => &[2]u8{ @tagName(tag)[0], 'x' },
                .byte => &[2]u8{ @tagName(tag)[0], 'l' },
            },
            inline .src, .dst, .stack, .base => |tag| name: {
                const middle = switch (tag) {
                    .src => "si",
                    .dst => "di",
                    .stack => "sp",
                    .base => "bp",
                    else => comptime unreachable,
                };

                break :name switch (reg.size) {
                    .qword => "r" ++ middle,
                    .dword => "e" ++ middle,
                    .word => middle,
                    .byte => middle ++ "l",
                };
            },
            inline else => |tag| name: {
                const prefix = comptime "r" ++ @tagName(tag);
                break :name switch (reg.size) {
                    .qword => prefix,
                    .dword => prefix ++ "d",
                    .word => prefix ++ "w",
                    .byte => prefix ++ "b",
                };
            },
        };
    }
};

pub inline fn markInitialized(as: *Assembler, registers: std.EnumSet(Gpr.Tag)) void {
    as.uninitialized_gprs.setIntersection(registers.complement());
}

pub fn preventClobbering(as: *Assembler, registers: std.EnumSet(Gpr.Tag)) void {
    const check_clobber_uninit = as.uninitialized_gprs.intersectWith(registers);
    if (check_clobber_uninit.count() != 0) {
        @branchHint(.cold);
        std.debug.panic(
            "can't prevent clobber of uninitialized: {f}",
            .{Gpr.Tag.setFormatter(check_clobber_uninit)},
        );
    }
    as.no_clobber_gprs.setUnion(registers);
}

pub fn allowClobbering(as: *Assembler, register: std.EnumSet(Gpr.Tag)) void {
    as.no_clobber_gprs = as.no_clobber_gprs.differenceWith(register);
}

/// Asserts that `register` is currently prevented from being clobbered
pub fn allowClobberingStrict(as: *Assembler, registers: std.EnumSet(Gpr.Tag)) void {
    const check_no_clobber = as.uninitialized_gprs.intersectWith(registers);
    if (check_no_clobber.count() != 0) {
        @branchHint(.cold);
        std.debug.panic(
            "already marked no clobber: {f}",
            .{Gpr.Tag.setFormatter(check_no_clobber)},
        );
    }

    as.allowClobbering(registers);
}

pub fn nextUninitializedRegister(as: *Assembler) Gpr.Tag {
    var iter = as.uninitialized_gprs.iterator();
    const chosen = iter.next() orelse @panic("out of registers!");
    std.debug.assert(!as.no_clobber_gprs.contains(chosen));
    return chosen;
}

inline fn printGpr(as: *Assembler, gpr: Gpr) void {
    as.print(gpr.name());
}

