/// https://www.felixcloutier.com/x86/ud
pub fn ud2(as: *Assembler) void {
    as.instr("ud2", &.{}, "");
}

pub fn finish(as: *Assembler) void {
    std.debug.assert(as.function_name == null);
    as.out.interface.flush() catch unreachable;
    as.* = undefined;
}

pub const OpcodeHandler = struct {
    function: Function,
    out_of_fuel: Label,

    pub fn end(handler: *OpcodeHandler, as: *Assembler) void {
        handler.out_of_fuel.place(as);
        as.jmp(.{ .symbol = .out_of_fuel_handler }, "");
        as.ud2();

        handler.function.end(as);
        handler.* = undefined;
    }

    pub fn jmpToNextHandler(
        handler: *const OpcodeHandler,
        as: *Assembler,
        temp: Gpr,
    ) void {
        // TODO: Store fuel directly instead of via pointer, include fuel in return value
        // System V supports two return registers
        std.debug.assert(temp.size == .qword);
        as.movzx(temp, .{ .mem = .{ .size = .byte, .base = .vip } }, "read next opcode byte");
        as.sub(.{ .mem = .{ .size = .qword, .base = .fuel } }, .{ .u8 = 1 }, "fuel check");
        as.jcc(.b, .{ .label = &handler.out_of_fuel }, "");
        as.writeComment("jump to the next handler");
        as.inc(.{ .gpr = .vip }, "vip");
        // \\    mov {[temp]t}, qword ptr [{[disp]t} + {[temp]t} * 8]
        as.mov(
            .{ .gpr = temp },
            .{ .mem = .{ .size = .qword, .base = .disp, .index = temp, .scale = .@"8" } },
            "load next handler",
        );
        as.jmp(.{ .gpr = temp }, "");
        as.ud2();
    }
};

pub fn defineOpcodeHandler(
    as: *Assembler,
    zig: *ZigWriter,
    name: []const u8,
    alignment: std.mem.Alignment,
) OpcodeHandler {
    const func = as.startFunction(name, alignment);
    zig.defineOpcodeHandler(name);
    const interpreter_state = comptime Gpr.sliceToTagSet(&Gpr.interpreter_state);
    as.markInitialized(interpreter_state);
    as.preventClobbering(
        as.no_clobber_gprs
            .unionWith(comptime interpreter_state.unionWith(.initMany(&.{ .stack, .base })))
            .differenceWith(.initOne(Gpr.vip.tag)),
    );
    return .{ .function = func, .out_of_fuel = as.label("out_of_fuel") };
}

pub fn restoreSystemVSavedRegisters(as: *Assembler) void {
    as.writeComment("restore System V callee-saved registers");
    for (0.., Gpr.Tag.system_v_callee_saved) |i, tag| {
        as.mov(.{ .gpr = Gpr.qword(tag) }, .paramFromRbp(i, .qword), "");
    }
}

